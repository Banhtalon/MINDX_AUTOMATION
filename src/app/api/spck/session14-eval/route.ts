import { NextResponse } from "next/server";
import {
  buildEnrichedSession14EvalList,
  session14ClassSummaryRepo,
  session14EvalRepo,
} from "@/lib/db/sqlite";
import {
  buildClassSession14SummaryDraft,
  compileSession14SummaryHtml,
  getEffectiveClassSession14Summary,
} from "@/lib/local-files/spck-demo-score-reader";
import { validateLocalRequest } from "@/lib/security/local-guard";

export async function GET(req: Request) {
  const guard = validateLocalRequest(req);
  if (guard) return guard;

  try {
    const { searchParams } = new URL(req.url);
    const classId = String(searchParams.get("classId") || "").trim().toUpperCase();
    if (!classId) {
      return NextResponse.json(
        { success: false, error: "Thiếu mã lớp (classId)." },
        { status: 400 }
      );
    }

    const records = buildEnrichedSession14EvalList(classId);
    const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
    return NextResponse.json({
      success: true,
      classId,
      records,
      rankings,
      classSummary,
    });
  } catch (err) {
    return NextResponse.json(
      {
        success: false,
        error: err instanceof Error ? err.message : String(err),
      },
      { status: 500 }
    );
  }
}

export async function POST(req: Request) {
  const guard = validateLocalRequest(req);
  if (guard) return guard;

  try {
    const body = await req.json();
    const classId = String(body?.classId || "").trim().toUpperCase();
    const action = String(body?.action || "save_draft").trim();

    if (!classId) {
      return NextResponse.json(
        { success: false, error: "Thiếu mã lớp (classId)." },
        { status: 400 }
      );
    }

    if (action === "save_class_summary") {
      const generated = buildClassSession14SummaryDraft(classId);
      const title =
        typeof body?.title === "string" && body.title.trim()
          ? body.title.trim()
          : generated.title;
      const bodyText =
        typeof body?.bodyText === "string" ? body.bodyText.trim() : generated.bodyText;
      const summaryHtml =
        typeof body?.summaryHtml === "string" && body.summaryHtml.trim()
          ? body.summaryHtml.trim()
          : compileSession14SummaryHtml(title, bodyText);
      const classSummary = session14ClassSummaryRepo.saveTeacherDraft({
        classId,
        title,
        bodyText,
        summaryHtml,
        approve: Boolean(body?.approve),
      });
      return NextResponse.json({
        success: true,
        classId,
        classSummary,
        rankings: generated.rankings,
        records: buildEnrichedSession14EvalList(classId),
      });
    }

    if (action === "reset_class_summary") {
      const generated = buildClassSession14SummaryDraft(classId);
      const classSummary = session14ClassSummaryRepo.saveAutoGenerated({
        classId,
        title: generated.title,
        bodyText: generated.bodyText,
        summaryHtml: generated.summaryHtml,
        forceOverwriteEdited: true,
      });
      return NextResponse.json({
        success: true,
        classId,
        classSummary,
        rankings: generated.rankings,
        records: buildEnrichedSession14EvalList(classId),
      });
    }

    if (action === "approve") {
      const isolatePerStudent = Boolean(body?.isolatePerStudent || body?.allowPartial);
      const studentIds: string[] = Array.isArray(body?.studentIds)
        ? body.studentIds.map((s: unknown) => String(s || "").trim()).filter(Boolean)
        : body?.studentId
        ? [String(body.studentId).trim()]
        : [];

      if (studentIds.length === 0) {
        return NextResponse.json(
          { success: false, error: "Thiếu danh sách học viên (studentIds) cần duyệt." },
          { status: 400 }
        );
      }

      const approvedIds: string[] = [];
      const errors: Array<{ studentId: string; error: string; conflict?: boolean }> = [];
      let hasConflict = false;
      const hasExpectedVersionsProp = body?.expectedVersions !== undefined;
      const expectedVersionsMap =
        hasExpectedVersionsProp &&
        body.expectedVersions &&
        typeof body.expectedVersions === "object" &&
        !Array.isArray(body.expectedVersions)
          ? (body.expectedVersions as Record<string, unknown>)
          : null;

      if (hasExpectedVersionsProp && !expectedVersionsMap) {
        const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
        return NextResponse.json(
          {
            success: false,
            approvedIds: [],
            error: "Trường expectedVersions phải là đối tượng bản đồ phiên bản hợp lệ.",
            records: buildEnrichedSession14EvalList(classId),
            rankings,
            classSummary,
          },
          { status: 400 }
        );
      }

      const validatedVersions = new Map<string, number>();
      for (const sid of studentIds) {
        const rawVer = expectedVersionsMap
          ? Object.prototype.hasOwnProperty.call(expectedVersionsMap, sid)
            ? expectedVersionsMap[sid]
            : undefined
          : studentIds.length === 1
          ? body?.expectedVersion
          : undefined;

        if (
          typeof rawVer !== "number" ||
          !Number.isFinite(rawVer) ||
          !Number.isInteger(rawVer) ||
          rawVer < 1
        ) {
          if (isolatePerStudent) {
            const current = session14EvalRepo.getOrInit(classId, sid);
            validatedVersions.set(sid, current.draftVersion);
          } else {
            errors.push({
              studentId: sid,
              error: `Thiếu phiên bản khóa (expectedVersion) hợp lệ cho học viên ${sid} khi duyệt.`,
            });
          }
        } else {
          validatedVersions.set(sid, rawVer);
        }
      }

      if (!isolatePerStudent && errors.length > 0) {
        const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
        return NextResponse.json(
          {
            success: false,
            approvedIds: [],
            errors,
            error: errors[0].error,
            records: buildEnrichedSession14EvalList(classId),
            rankings,
            classSummary,
          },
          { status: 400 }
        );
      }

      if (!isolatePerStudent) {
        // Pre-check all versions before mutating any student record
        for (const sid of studentIds) {
          const current = session14EvalRepo.getOrInit(classId, sid);
          const expectedVer = validatedVersions.get(sid)!;
          if (current.draftVersion !== expectedVer) {
            hasConflict = true;
            errors.push({
              studentId: sid,
              conflict: true,
              error: `Bản nháp đánh giá Buổi 14 của học viên ${sid} đã thay đổi (expected=${expectedVer}, current=${current.draftVersion}).`,
            });
          }
        }

        if (hasConflict) {
          const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
          return NextResponse.json(
            {
              success: false,
              conflict: true,
              approvedIds: [],
              errors,
              error: errors[0].error,
              records: buildEnrichedSession14EvalList(classId),
              rankings,
              classSummary,
            },
            { status: 409 }
          );
        }
      }

      for (const sid of studentIds) {
        const expectedVer = validatedVersions.get(sid);
        if (expectedVer === undefined) continue;
        const res = session14EvalRepo.approveDraft(classId, sid, expectedVer);
        if (res.success) {
          approvedIds.push(sid);
        } else {
          if (res.conflict) hasConflict = true;
          errors.push({
            studentId: sid,
            error: res.error || "Không thể duyệt bản ghi.",
            conflict: res.conflict,
          });
        }
      }

      const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
      const okOverall = isolatePerStudent ? approvedIds.length > 0 || errors.length === 0 : errors.length === 0;
      const httpStatus = okOverall ? 200 : hasConflict ? 409 : 400;

      return NextResponse.json(
        {
          success: okOverall,
          partialFailure: isolatePerStudent && errors.length > 0 ? true : undefined,
          conflict: hasConflict || undefined,
          approvedIds,
          errors,
          error: !okOverall && errors.length > 0 ? errors[0].error : undefined,
          records: buildEnrichedSession14EvalList(classId),
          rankings,
          classSummary,
        },
        { status: httpStatus }
      );
    }

    // Default: save_draft for a single student
    const studentId = String(body?.studentId || "").trim();
    if (!studentId) {
      return NextResponse.json(
        { success: false, error: "Thiếu mã học viên (studentId)." },
        { status: 400 }
      );
    }

    const saved = session14EvalRepo.saveDraft({
      classId,
      studentId,
      expectedVersion:
        typeof body?.expectedVersion === "number" && Number.isFinite(body.expectedVersion)
          ? body.expectedVersion
          : undefined,
      competencyScores: body?.competencyScores,
      demoScores: body?.demoScores,
      demoRawTotalScore:
        typeof body?.demoRawTotalScore === "number" ? body.demoRawTotalScore : undefined,
      demoSourcePath: body?.demoSourcePath,
      demoJudgeNote: body?.demoJudgeNote,
      learnedFromMindx: body?.learnedFromMindx,
      suggestionsFromMindx: body?.suggestionsFromMindx,
      futureDirection: body?.futureDirection,
      awardRanking: body?.awardRanking,
      awardRankGrade:
        body?.awardRankGrade !== undefined
          ? body.awardRankGrade === null || body.awardRankGrade === ""
            ? null
            : Math.min(5, Math.max(0, Math.round(Number(body.awardRankGrade))))
          : undefined,
      quickTags: body?.quickTags,
      teacherNote: body?.teacherNote,
    });

    if (saved.conflict) {
      const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
      return NextResponse.json(
        {
          success: false,
          conflict: true,
          currentVersion: saved.currentVersion,
          record: saved.record,
          rankings,
          classSummary,
          error: `Bản nháp đánh giá Buổi 14 đã có phiên bản mới hơn (${saved.currentVersion}).`,
        },
        { status: 409 }
      );
    }

    const records = buildEnrichedSession14EvalList(classId);
    const { classSummary, rankings } = getEffectiveClassSession14Summary(classId);
    return NextResponse.json({
      success: true,
      record: saved.record,
      records,
      rankings,
      classSummary,
    });
  } catch (err) {
    return NextResponse.json(
      {
        success: false,
        error: err instanceof Error ? err.message : String(err),
      },
      { status: 500 }
    );
  }
}
